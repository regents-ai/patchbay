defmodule Patchbay.Repo.Migrations.AgentRepairsStartRunning do
  @moduledoc """
  The Patchbay Agent's repairs run as an AshOban job (`Patchbay.Forum.Report`'s
  `:repair_by_agent`), which writes an attempt only when it starts one, so an
  attempt begins at `running` and the `queued` status is gone.

  Generated by `mix ash.codegen` for the column default. Its `up` also ends any
  attempt still at `queued`: under the old loop that was a repair that stopped
  before it started, so it ends the way the job's give-up path ends one, as
  `errored` with that detail and its update time, and the count it ended is
  printed in the release step. `down` puts the default back and leaves those
  rows as they are: `errored` is a status every version reads.
  """

  use Ecto.Migration

  # The table is named in the repo's own schema (`Patchbay.Repo.default_prefix/0`),
  # which in production is not on the connection's search path. It is one of the
  # two names runtime.exs allows, so the statement for each is written here.
  @end_queued """
  UPDATE SCHEMA.forum_repair_attempts
  SET status = 'errored',
      detail = 'the repair stopped before it started',
      updated_at = (now() AT TIME ZONE 'utc')
  WHERE status = 'queued'
  """
  @end_queued_public String.replace(@end_queued, "SCHEMA.", "public.")
  @end_queued_patchbay_app String.replace(@end_queued, "SCHEMA.", "patchbay_app.")

  # The site's own reads wait at most five seconds for a lock
  # (`Patchbay.DatabaseConfig`), so the change gives up after two rather than hold
  # them behind a long transaction; run migrate again.
  def up do
    execute "SET LOCAL lock_timeout = '2s'"

    alter table(:forum_repair_attempts) do
      modify :status, :text, default: "running"
    end

    # The table is locked from here to the end, so the count printed is the
    # count that commits.
    flush()

    %{num_rows: ended} = repo().query!(end_queued(Patchbay.Repo.default_prefix()))
    IO.puts("forum_repair_attempts: #{ended} queued attempt(s) ended as errored")
  end

  def down do
    execute "SET LOCAL lock_timeout = '2s'"

    alter table(:forum_repair_attempts) do
      modify :status, :text, default: "queued"
    end
  end

  defp end_queued("public"), do: @end_queued_public
  defp end_queued("patchbay_app"), do: @end_queued_patchbay_app
end
