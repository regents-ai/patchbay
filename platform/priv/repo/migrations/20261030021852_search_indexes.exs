defmodule Patchbay.Repo.Migrations.SearchIndexes do
  @moduledoc """
  The indexes a search and the questions list read instead of every row: the
  stored words of threads, replies, cards and sites (`search_vector`, the
  previous migration), a thread's title spelled a little wrong, its exact tool
  names, and published questions newest first (`Patchbay.Forum.Feed`).

  Generated by `mix ash.codegen`, with the drops before each create added by
  hand. Each index is built without stopping writes (`CONCURRENTLY`), outside a
  transaction. A build that stops part way leaves an unusable index behind, so
  each create first drops one of the same name; running migrate again builds
  them all afresh.
  """

  use Ecto.Migration

  @disable_ddl_transaction true
  @disable_migration_lock true

  @indexes [
    {:forum_replies, [:search_vector], using: "GIN"},
    {:forum_reports, [:search_vector], using: "GIN"},
    {:forum_reports, ["title public.gin_trgm_ops"],
     name: "forum_reports_title_trgm_index", using: "GIN"},
    {:forum_reports, [:tool_names], using: "GIN"},
    {:forum_reports, [:inserted_at, :id],
     name: "forum_reports_feed_index",
     where: "visibility = 'published' AND techtree_digest IS NULL"},
    {:forum_solution_cards, [:search_vector], using: "GIN"},
    {:forum_sites, [:search_vector], using: "GIN"}
  ]

  # A build waits for the reads already open on its table, never stops new
  # ones, and gives up after two seconds of waiting; run migrate again. The
  # setting holds for this connection only and is put back at the end.
  def up do
    execute "SET lock_timeout = '2s'"

    for {table, columns, options} <- @indexes do
      drop_if_exists index(table, columns, Keyword.take(options, [:name]) ++ [concurrently: true])
      create index(table, columns, options ++ [concurrently: true])
    end

    execute "RESET lock_timeout"
  end

  def down do
    execute "SET lock_timeout = '2s'"

    for {table, columns, options} <- Enum.reverse(@indexes) do
      drop_if_exists index(table, columns, Keyword.take(options, [:name]) ++ [concurrently: true])
    end

    execute "RESET lock_timeout"
  end
end
